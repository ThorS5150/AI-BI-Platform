"""Answer step: retrieved passages go to the LLM. An answer is only returned if the passages cover the question."""
import re
from dataclasses import dataclass
from typing import Protocol

from modules.rag.retriever import Hit, Retriever

NOT_FOUND_TOKEN = "NOT_FOUND"
FALLBACK_TEXT = (
    "I could not find this in the Demo Auto policies. "
    "/ Je n'ai rien trouvé à ce sujet dans les politiques de Demo Auto."
)

# Instructions for the LLM 
SYSTEM_PROMPT = (
    "You answer questions about the policies of Demo Auto Québec Inc. "
    "Use only the passages in the context. Answer in the language of the question. "
    "Be brief and state the rule precisely (numbers, durations, conditions). "
    "Prohibitions, limits and exclusions are answers too: if the passages say something is not permitted "
    "or not covered, answer 'No' and state the rule. "
    f"Reply with exactly {NOT_FOUND_TOKEN} and nothing else only if no passage addresses the topic of the question. "
    "At the end of your answer, add the labels you relied on after 'Sources used:', copied exactly "
    "from the context brackets, e.g. Sources used: [01_discount_policy.md 1.2]. "
    f"If you reply {NOT_FOUND_TOKEN}, do not add a sources line."
)

SOURCES_LINE_RE = re.compile(r"Sources used:\s*(.+)$", re.MULTILINE | re.IGNORECASE)
CITATION_RE = re.compile(r"([\w\-]+\.md\s+\d+\.\d+)")


class LLMClient(Protocol):
    def chat(self, system: str, user: str) -> str: ...


@dataclass
class Answer:
    text: str
    sources: list[str]
    found: bool

# method is called during the answer() method below to send user context to the llm
def build_user_prompt(question: str, hits: list[Hit]) -> str:
    context = "\n\n".join(f"[{h.chunk.doc} {h.chunk.section}] {h.chunk.text}" for h in hits)
    return f"Context:\n{context}\n\nQuestion: {question}"


def split_sources(raw: str, hits: list[Hit]) -> tuple[str, list[str]]:
    """Removes the 'Sources used' part and keeps only cited sources that were actually retrieved.

    Citations the model invents are dropped. If no valid citation remains, the top-1 hit is shown.
    """
    available = list(dict.fromkeys(f"{h.chunk.doc} {h.chunk.section}" for h in hits))
    match = SOURCES_LINE_RE.search(raw) # match generated by calling the search function of the SOURES_LINE_RE constant
    if not match:
        return raw, available[:1]
    text = (raw[:match.start()] + raw[match.end():]).strip()
    cited = [" ".join(c.split()) for c in CITATION_RE.findall(match.group(1))]
    sources = [s for s in available if s in cited]
    return text, sources or available[:1]

# method called by the agent when user asks question in the chatbot
def answer(question: str, retriever: Retriever, llm: LLMClient) -> Answer:
    hits = retriever.search(question)  # hits are created by the search() method within the retriever modul; only hits above MIN_SCORE
    if not hits: # if no hits generated (e.g. MIN_SCORE threshold) in the search prozess within the chunks and answer will be standard text defined above
        return Answer(FALLBACK_TEXT, [], False)
    # LLM is called for processing the answer
    raw = llm.chat(SYSTEM_PROMPT, build_user_prompt(question, hits)).strip()
    if raw.startswith(NOT_FOUND_TOKEN): # if no answers found in the search prozess within the chunks and answer will be standard text defined above
        return Answer(FALLBACK_TEXT, [], False)
    # Build text ans sources for answer send as an instance of the class Answer
    text, sources = split_sources(raw, hits)
    if not text:
        return Answer(FALLBACK_TEXT, [], False)
    return Answer(text, sources, True)